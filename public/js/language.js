  const originals = new WeakMap();
  let applying = false;
  let language = localStorage.getItem("eamwifi_language") || "en";
  function translateNode(node) {
    if (applying || node.nodeType !== Node.TEXT_NODE) return;
    const raw = originals.has(node) ? originals.get(node) : node.nodeValue;
    if (!originals.has(node)) originals.set(node, raw);
    const source = raw.trim();
    if (!source) return;
    let result = raw;
    if (language === "sw") {
      if (translations[source]) result = raw.replace(source, translations[source]);
      else {
        for (const [en, sw] of Object.entries(translations)) {
          if (source.startsWith(en) && source.length > en.length) {
            result = raw.replace(en, sw);
            break;
          }
        }
      }
    }
    if (node.nodeValue !== result) {
      applying = true;
      node.nodeValue = result;
      applying = false;
    }
  }
  function translateTree(root) {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) translateNode(node);
    if (root.querySelectorAll) root.querySelectorAll("input[placeholder],textarea[placeholder],button[title]").forEach(el => {
      const attrs = ["placeholder","title"];
      attrs.forEach(attr => {
        const original = el.dataset["i18n" + attr] || el.getAttribute(attr);
        if (!el.dataset["i18n" + attr]) el.dataset["i18n" + attr] = original || "";
        if (language === "sw" && translations[original]) el.setAttribute(attr, translations[original]);
        else if (original) el.setAttribute(attr, original);
      });
    });
  }
  function applyLanguage() {
    translateTree(document.body);
    const picker = document.getElementById("eam-language");
    if (picker && picker.value !== language) picker.value = language;
    document.documentElement.lang = language;
  }
  const picker = document.getElementById("eam-language");
  if (picker) {
    picker.value = language;
    picker.addEventListener("change", () => {
      language = picker.value;
      localStorage.setItem("eamwifi_language", language);
      applyLanguage();
    });
  }
  applyLanguage();
  new MutationObserver(records => {
    records.forEach(record => {
      if (record.type === "characterData") translateNode(record.target);
      record.addedNodes?.forEach(node => {
        if (node.nodeType === Node.TEXT_NODE) translateNode(node);
        else if (node.nodeType === Node.ELEMENT_NODE) translateTree(node);
      });
    });
  }).observe(document.body, {subtree:true,childList:true,characterData:true});
